"""Render scan and match results as reviewable Markdown."""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

PRIORITY_ORDER = {"high": 0, "medium": 1, "low": 2, "none": 3}


def _snippet(text: str) -> str:
    return text.replace("`", "'")


def scan_to_markdown(result: dict, root: Path) -> str:
    summary = result["summary"]
    corpus = result["corpus"]
    lines = [
        "# POHE harness pattern scan",
        "",
        f"- Repository: `{root.resolve()}`",
        f"- Files scanned: {corpus['files_scanned']} "
        f"({corpus['code']} code, {corpus['test']} test, {corpus['support']} support)",
        f"- Records with a retrieved cue: {summary['observed']} of {summary['records']}",
        f"- High-review-priority records: {summary['high_priority']}",
        "",
        "> **Evidence boundary.** A hit is a retrieval cue (E1), not a confirmed",
        "> implementation, pointcut match, or contract proof. Absence of a cue is not",
        "> evidence of absence. Coverage here is descriptive of this checkout only.",
        "",
        "## Family coverage",
        "",
        "| Family | Observed | Records |",
        "| --- | ---: | ---: |",
    ]
    names = {"P": "Coding-agent mechanisms", "W": "Workflows & coordination", "C": "Communication", "R": "Reasoning & feedback", "E": "Harness evolution"}
    for key in ("P", "W", "C", "R", "E"):
        bucket = summary["by_family"].get(key, {"observed": 0, "total": 0})
        lines.append(f"| {key} — {names[key]} | {bucket['observed']} | {bucket['total']} |")
    lines.append("")

    observed = [item for item in result["patterns"] if item["status"] == "observed"]
    observed.sort(key=lambda item: (PRIORITY_ORDER[item["priority"]], item["id"]))
    lines.append("## Records with a retrieval cue")
    lines.append("")
    if not observed:
        lines.append("No frozen cue matched this checkout. Review the vocabulary before concluding that a mechanism is absent.")
        lines.append("")
    for item in observed:
        lines.append(f"### {item['id']} — {item['name']}")
        lines.append("")
        lines.append(f"- Priority: **{item['priority']}**  |  Evidence level: **E1 retrieval cue**")
        lines.append(f"- Cue hits: {item['hits']} across {item['files']} files "
                     f"({item['code_files']} code, {item['test_files']} test, {item['support_files']} support)")
        lines.append(f"- Join point: `{item['join_point']}`")
        lines.append("")
        lines.append("Representative matches:")
        lines.append("")
        for match in item["matches"][:5]:
            lines.append(f"- `{match['file']}:{match['line']}` — `{_snippet(match['text'])}`")
        if item["truncated"]:
            lines.append("- Additional matches are omitted from this report.")
        lines.append("")
        lines.append("Contract to verify:")
        lines.append("")
        lines.append(f"- Requires: {item['contract']['requires']}")
        lines.append(f"- Ensures: {item['contract']['ensures']}")
        lines.append(f"- Invariant: {item['contract']['invariant']}")
        lines.append(f"- Violation: {item['contract']['violation']}")
        lines.append(f"- Negative control: {item['negative_control']}")
        lines.append("")
        lines.append(f"Next step: {item['next_step']}")
        lines.append("")

    unseen = [item for item in result["patterns"] if item["status"] == "not_observed"]
    if unseen:
        lines.append("## Records without a retrieved cue")
        lines.append("")
        lines.append(", ".join(f"{item['id']} {item['name']}" for item in unseen))
        lines.append("")
        lines.append("These records are unobserved by this cue pass, not disproved. Vocabulary, file layout, generated code, and missing subsystems all change detector yield.")
        lines.append("")

    lines.extend([
        "## Review checklist",
        "",
        "1. Open the representative matches and decide whether the mechanism is real.",
        "2. Check context, trigger, structure, and effect separately.",
        "3. Map each contract field to code, tests, or a runtime check.",
        "4. Apply the negative control: find a similar-looking construct that must not count.",
        "5. Record the result as E1, E2, or E3; never promote from a cue alone.",
        "6. Keep unobserved records visible as unobserved.",
        "",
        "## Commands",
        "",
        "```bash",
        "pohe-agent scan <repo> --json findings.json --markdown findings.md",
        "pohe-agent match <repo> --pattern P01",
        "pohe-agent plan <repo> --findings findings.json --goal \"harden the runtime\" -o evolution.md",
        "```",
        "",
        f"_Generated by pohe-agent on {datetime.now(timezone.utc).date().isoformat()}._",
        "",
    ])
    return "\n".join(lines)


def match_to_markdown(result: dict) -> str:
    lines = [
        "# Structural candidates",
        "",
        f"Repository: `{result['root']}`",
        f"Files scanned: {result['corpus']['files_scanned']}; symbols extracted: {result['corpus']['symbols_extracted']}",
        "",
        "> Structural symbols narrow inspection. They do not establish a pointcut match or a contract.",
        "",
    ]
    for item in result["patterns"]:
        lines.append(f"## {item['id']} — {item['name']}")
        lines.append("")
        if not item["candidates"]:
            lines.append("No symbol-level candidate found.")
            lines.append("")
            continue
        lines.append(f"{len(item['candidates'])} candidate(s):")
        lines.append("")
        for candidate in item["candidates"][:25]:
            lines.append(f"- `{candidate['file']}:{candidate['line']}` — `{candidate['symbol']}` ({candidate['kind']}, {candidate['reason']})")
        if len(item["candidates"]) > 25:
            lines.append(f"- … {len(item['candidates']) - 25} more")
        lines.append("")
        lines.append("Adjudication questions:")
        lines.append("")
        for question in item["questions"]:
            lines.append(f"- [ ] {question}")
        lines.append("")
    return "\n".join(lines)
